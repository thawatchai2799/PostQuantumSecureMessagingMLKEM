"""
gen_s2_tables.py — Export trained canonical-Huffman tables to s2_tables.h.

A canonical table is fully described by its 257 code lengths (bytes 0-255
+ EOF=256). The C side reconstructs the exact same codes from lengths
using the same canonical rule, so exporting lengths alone guarantees
bit-identical behavior between the Python reference and the C encoder.
"""

import pathlib

from s2_huffman import HuffmanTable, EOF

TABLES = {
    "en":  "s2_train.txt",
    "c2":  "s2_train_c2.txt",
    "c3":  "s2_train_c3.txt",
}


def emit(name: str, table: HuffmanTable) -> str:
    lens = [table.lengths[s] for s in range(257)]
    rows = []
    for i in range(0, 257, 16):
        rows.append("    " + ", ".join(f"{v:2d}" for v in lens[i:i + 16]) + ",")
    body = "\n".join(rows).rstrip(",")
    return (f"static const uint8_t S2_LEN_{name.upper()}[257] = {{\n{body}\n}};\n")


def main() -> int:
    out = ["/* AUTO-GENERATED by gen_s2_tables.py — do not edit.",
           " * Canonical Huffman code lengths for symbols 0..255 + EOF(256).",
           " * Training corpora (seeds reported in the paper):",
           " *   en: s2_train.txt | c2: s2_train_c2.txt | c3: s2_train_c3.txt */",
           "#ifndef S2_TABLES_H", "#define S2_TABLES_H", "#include <stdint.h>", ""]
    for name, path in TABLES.items():
        t = HuffmanTable.train(pathlib.Path(path).read_bytes())
        assert t.lengths[EOF] > 0
        out.append(emit(name, t))
        print(f"{name}: max code length {t.max_len}")
    out.append("#endif /* S2_TABLES_H */")
    pathlib.Path("s2_tables.h").write_text("\n".join(out))
    print("wrote s2_tables.h")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
