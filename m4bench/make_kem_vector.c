/* make_kem_vector.c - host program that writes kem_vector.h.
 *
 * Runs the derandomized ML-KEM-512 key exchange of kem_glue.c (mlkem-native,
 * C backend) from two fixed seed strings and writes the SHA3-256 digest of
 * pk || ct || ss to kem_vector.h; the firmware recomputes the digest on the
 * device and compares. When built with -DHAVE_LIBOQS, the same coins are
 * also fed to liboqs (OQS_KEM_keypair_derand / OQS_KEM_encaps_derand) and
 * pk, sk, ct and ss are required to match byte for byte, so that the device
 * implementation is tied to the library that produced the host timings.
 *
 * Build (from the repository root):
 *   gcc -std=c99 -O2 -I third_party/mlkem-native/mlkem -DMLK_CONFIG_PARAMETER_SET=512 \
 *       -I m4bench m4bench/make_kem_vector.c m4bench/kem_glue.c \
 *       third_party/mlkem-native/mlkem/mlkem_native.c -o build/make_kem_vector \
 *       [-DHAVE_LIBOQS -I<oqs>/include <oqs>/lib/liboqs.so -Wl,-rpath,<oqs>/lib]
 *   build/make_kem_vector m4bench/kem_vector.h
 */
#include <stdio.h>
#include <string.h>

#include "kem_glue.h"
#ifdef HAVE_LIBOQS
#include <oqs/oqs.h>
#endif

static const char KP_SEED[] = "m4bench ML-KEM-512 keypair coins v1";
static const char ENC_SEED[] = "m4bench ML-KEM-512 encaps coins v1";

int main(int argc, char **argv) {
    if (argc != 2) { fprintf(stderr, "usage: make_kem_vector <output header>\n"); return 2; }
    static uint8_t pk[KEM_PK_BYTES], sk[KEM_SK_BYTES], ct[KEM_CT_BYTES];
    uint8_t ss[KEM_SS_BYTES], coins_kp[64], coins_enc[32], digest[32];
    if (!kem_derand_raw(KP_SEED, ENC_SEED, pk, sk, ct, ss, coins_kp, coins_enc)) {
        fprintf(stderr, "mlkem-native: derandomized key exchange failed\n");
        return 1;
    }
    if (!kem_derand_digest(KP_SEED, ENC_SEED, digest)) {
        fprintf(stderr, "mlkem-native: digest run failed\n");
        return 1;
    }
    const char *cross = "not cross-checked (built without liboqs)";
#ifdef HAVE_LIBOQS
    {
        static uint8_t pk2[KEM_PK_BYTES], sk2[KEM_SK_BYTES], ct2[KEM_CT_BYTES];
        uint8_t ss2[KEM_SS_BYTES], ss3[KEM_SS_BYTES];
        OQS_KEM *kem = OQS_KEM_new(OQS_KEM_alg_ml_kem_512);
        if (!kem) { fprintf(stderr, "liboqs: ML-KEM-512 not enabled\n"); return 1; }
        if (kem->length_keypair_seed != 64 || kem->length_encaps_seed != 32) {
            fprintf(stderr, "liboqs: unexpected seed lengths %zu/%zu\n",
                    kem->length_keypair_seed, kem->length_encaps_seed);
            return 1;
        }
        if (OQS_KEM_keypair_derand(kem, pk2, sk2, coins_kp) != OQS_SUCCESS ||
            OQS_KEM_encaps_derand(kem, ct2, ss2, pk2, coins_enc) != OQS_SUCCESS ||
            OQS_KEM_decaps(kem, ss3, ct2, sk2) != OQS_SUCCESS) {
            fprintf(stderr, "liboqs: derandomized key exchange failed\n");
            return 1;
        }
        if (memcmp(pk, pk2, KEM_PK_BYTES) || memcmp(sk, sk2, KEM_SK_BYTES) ||
            memcmp(ct, ct2, KEM_CT_BYTES) || memcmp(ss, ss2, KEM_SS_BYTES) || memcmp(ss, ss3, KEM_SS_BYTES)) {
            fprintf(stderr, "MISMATCH between mlkem-native C backend and liboqs\n");
            return 1;
        }
        static char buf[96];
        snprintf(buf, sizeof buf, "cross-checked against liboqs %s: pk, sk, ct, ss identical", OQS_version());
        cross = buf;
        OQS_KEM_free(kem);
    }
#endif
    FILE *f = fopen(argv[1], "w");
    if (!f) { perror(argv[1]); return 1; }
    fprintf(f, "/* kem_vector.h - generated by m4bench/make_kem_vector.c; do not edit.\n"
               " * Expected SHA3-256(pk || ct || ss) of the derandomized ML-KEM-512 key\n"
               " * exchange with coins SHAKE256(KP_SEED, 64) and SHAKE256(ENC_SEED, 32).\n"
               " * %s. */\n", cross);
    fprintf(f, "#ifndef KEM_VECTOR_H\n#define KEM_VECTOR_H\n#include <stdint.h>\n");
    fprintf(f, "#define KEM_VECTOR_KP_SEED \"%s\"\n#define KEM_VECTOR_ENC_SEED \"%s\"\n", KP_SEED, ENC_SEED);
    fprintf(f, "static const uint8_t KEM_VECTOR_DIGEST[32] = {");
    for (int i = 0; i < 32; i++) fprintf(f, "%s0x%02x", i ? ", " : "", digest[i]);
    fprintf(f, "};\n#endif\n");
    fclose(f);
    printf("wrote %s (%s)\ndigest: ", argv[1], cross);
    for (int i = 0; i < 32; i++) printf("%02x", digest[i]);
    printf("\n");
    return 0;
}
