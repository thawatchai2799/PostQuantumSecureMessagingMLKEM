"""
make_m4_data.py - Embed the benchmark inputs and their expected encoded
sizes into a C header for the on-device benchmark (m4bench).

The device cannot read files, so the slice-0 inputs of the host measurements
(corpus/<c>/<c>_<n>.txt, byte-identical to slice 0 of the five timing
slices) are compiled into flash, together with the encoded size that the
host pipeline produced for every (corpus, length, scheme) cell. The device
re-encodes each input, checks the round trip, and compares its encoded size
with the host's: a match proves that the device ran the same codec on the
same bytes and produced the same payload.

Lengths: 120, 500, 1,000, 2,000 and 5,000 characters (20,000 is left out:
the Unishox2 encoder's near-quadratic cost would take tens of seconds per
repetition at 16 MHz). Corpora: C1, C2, C3, the three with C timings on the
host. S1 is skipped on C2, as in the paper (lossy on JSON).

Usage (from the repository root):
    python3 m4bench/make_m4_data.py [--sizes data/results_c_sizes.csv]
Output: m4bench/m4_data.h
"""

import argparse
import csv
import hashlib
import pathlib

CORPORA = ["c1", "c2", "c3"]
LENGTHS = [120, 500, 1000, 2000, 5000]
# (C identifier, host scheme name in results_c_sizes.csv)
SCHEMES = [("S1", "S1-6bit"), ("S2", "S2-dom-bit"), ("HS8", "S5-hs8"),
           ("HS11", "S5-hs11"), ("UX", "S6-unishox")]


def c_bytes(data: bytes, per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", default="data/results_c_sizes.csv")
    ap.add_argument("--corpus", default="corpus")
    ap.add_argument("--out", default="m4bench/m4_data.h")
    args = ap.parse_args()

    sizes = {}
    with open(args.sizes, newline="") as f:
        for r in csv.DictReader(f):
            if r["slice"] == "0":
                sizes[(r["corpus"], int(r["length"]), r["scheme"])] = int(r["encoded_bytes"])

    out = ["/* m4_data.h - generated by m4bench/make_m4_data.py; do not edit. */",
           "#ifndef M4_DATA_H", "#define M4_DATA_H", "#include <stdint.h>", "",
           f"#define M4_NCORPORA {len(CORPORA)}", f"#define M4_NLENGTHS {len(LENGTHS)}",
           f"#define M4_NSCHEMES {len(SCHEMES)}", f"#define M4_MAXLEN {max(LENGTHS)}", "#define M4_MAXBYTES 5120   /* >= largest input in bytes */", "",
           "static const uint16_t M4_LENGTHS[M4_NLENGTHS] = {" + ", ".join(map(str, LENGTHS)) + "};",
           "static const char *const M4_CORPUS_NAME[M4_NCORPORA] = {" + ", ".join(f'"{c}"' for c in CORPORA) + "};",
           "static const char *const M4_SCHEME_NAME[M4_NSCHEMES] = {" + ", ".join(f'"{h}"' for _, h in SCHEMES) + "};",
           ""]
    digests = []
    for c in CORPORA:
        for n in LENGTHS:
            p = pathlib.Path(args.corpus) / c / f"{c}_{n}.txt"
            data = p.read_bytes()
            nchars = len(data.decode("utf-8"))
            if nchars != n:
                raise SystemExit(f"{p}: {nchars} characters, expected {n}")
            digests.append(f"{c}_{n}: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}")
            out.append(f"static const uint8_t M4_IN_{c}_{n}[{len(data)}] = {{   /* {n} characters */")
            out.append(c_bytes(data))
            out.append("};")
    out.append("")
    out.append("static const uint8_t *const M4_INPUT[M4_NCORPORA][M4_NLENGTHS] = {")
    for c in CORPORA:
        out.append("    {" + ", ".join(f"M4_IN_{c}_{n}" for n in LENGTHS) + "},")
    out.append("};")
    out.append("/* Input size in bytes (UTF-8); equals the character count except on C1, which holds a few non-ASCII characters. */")
    out.append("static const uint16_t M4_INPUT_BYTES[M4_NCORPORA][M4_NLENGTHS] = {")
    for c in CORPORA:
        out.append("    {" + ", ".join(f"sizeof M4_IN_{c}_{n}" for n in LENGTHS) + "},")
    out.append("};")
    out.append("")
    out.append("/* Host encoded size per (corpus, length, scheme); -1 = cell not measured on the host. */")
    out.append("static const int32_t M4_EXPECTED[M4_NCORPORA][M4_NLENGTHS][M4_NSCHEMES] = {")
    missing = []
    for c in CORPORA:
        out.append("    {")
        for n in LENGTHS:
            vals = []
            for _, host in SCHEMES:
                v = sizes.get((c, n, host))
                if v is None:
                    missing.append((c, n, host))
                    v = -1
                vals.append(str(v))
            out.append("        {" + ", ".join(vals) + "},")
        out.append("    },")
    out.append("};")
    out.append("")
    out.append("/* Input provenance (slice 0 of the host timing slices):")
    out.extend("   " + d for d in digests)
    out.append("*/")
    out.append("#endif")
    pathlib.Path(args.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {args.out}: {len(CORPORA) * len(LENGTHS)} inputs, {len(CORPORA) * sum(LENGTHS)} bytes")
    print("cells without a host size (skipped on the device):", missing)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
